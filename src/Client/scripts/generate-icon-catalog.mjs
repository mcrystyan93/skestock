import { readdirSync, writeFileSync } from 'node:fs';

const iconsDirectory = new URL('../src/assets/icons/', import.meta.url);
const catalogFile = new URL('../src/app/shared/icons/icon-catalog.generated.ts', import.meta.url);

const iconFileNames = readdirSync(iconsDirectory)
  .filter((fileName) => fileName.endsWith('.svg'))
  .sort((left, right) => left < right ? -1 : left > right ? 1 : 0);

const iconFileList = iconFileNames
  .map((fileName) => `  '${fileName}'`)
  .join(',\n');

writeFileSync(
  catalogFile,
  `// This file is generated by scripts/generate-icon-catalog.mjs.\n` +
    `export const ICON_ASSET_NAMES = [\n${iconFileList}\n] as const;\n`
);
